class Calculator:
    """A simple calculator class with basic arithmetic operations"""

    @staticmethod
    def add(a, b):
        """Return the sum of a and b"""
        return a + b

    @staticmethod
    def subtract(a, b):
        """Return the difference of a and b"""
        return a - b

    @staticmethod
    def multiply(a, b):
        """Return the product of a and b"""
        return a * b

    @staticmethod
    def divide(a, b):
        """Return the quotient of a and b"""
        return a / b
